export function getWordsForTier(tier: ArenaTier): VocabWord[] {
  const exact = VOCAB_BANK.filter((w) => w.tier === tier);
  if (tier === 'starter') return exact;
  if (tier === 'jungle') return [...exact, ...VOCAB_BANK.filter((w) => w.tier === 'starter').slice(0, 6)];
  return [...exact, ...VOCAB_BANK.filter((w) => w.tier === 'jungle').slice(0, 6)];
}

export function shuffleArray<T>(items: T[]): T[] {
  const copy = [...items];
  for (let i = copy.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [copy[i], copy[j]] = [copy[j], copy[i]];
  }
  return copy;
}
